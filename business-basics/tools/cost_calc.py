"""Recalculate drink costs from data/*.csv and rewrite 04-cost-breakdown.md.

Run from the business-basics folder:  python3 tools/cost_calc.py
"""
import csv
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"


def read(name):
    with open(DATA / name, newline="") as f:
        return list(csv.DictReader(f))


ingredients = {}
for row in read("ingredients.csv"):
    ingredients[row["ingredient"]] = {
        **row,
        "cost_per_unit": float(row["pack_price"]) / float(row["pack_size"]),
    }

prices = {(r["drink"], r["size"]): r["price"] for r in read("menu_prices.csv")}

drinks = OrderedDict()
problems = []
for r in read("recipes.csv"):
    key = (r["drink"], r["size"])
    ing = ingredients.get(r["ingredient"])
    if ing is None:
        problems.append(f"{r['drink']} {r['size']}: unknown ingredient '{r['ingredient']}'")
        continue
    amount = float(r["amount"])
    drinks.setdefault(key, []).append(
        (r["ingredient"], amount, ing["unit"], amount * ing["cost_per_unit"], r["notes"])
    )

out = ["# Cost Breakdown", "",
       "This file is generated by `tools/cost_calc.py`. Don't edit it by hand.",
       "Change prices in `data/ingredients.csv` and recipes in `data/recipes.csv`, then rerun.", "",
       "Target: keep drink cost under 25% of the menu price.", "",
       "## Summary", "",
       "| Drink | Size | Cost | Menu price | Cost % |",
       "|---|---|---|---|---|"]
for (drink, size), lines in drinks.items():
    total = sum(l[3] for l in lines)
    price = prices.get((drink, size), "")
    if price:
        pct = f"{total / float(price) * 100:.1f}%"
        flag = " (over 25%)" if total / float(price) > 0.25 else ""
        out.append(f"| {drink} | {size} | ${total:.2f} | ${float(price):.2f} | {pct}{flag} |")
    else:
        out.append(f"| {drink} | {size} | ${total:.2f} | (add) | |")

out += ["", "## Detail", ""]
for (drink, size), lines in drinks.items():
    out += [f"### {drink}, {size}", "", "| Ingredient | Amount | Cost | Note |", "|---|---|---|---|"]
    for name, amount, unit, cost, note in lines:
        out.append(f"| {name} | {amount:g} {unit} | ${cost:.3f} | {note} |")
    out.append(f"| **Total** | | **${sum(l[3] for l in lines):.2f}** | |")
    out.append("")

out += ["## Ingredient unit costs", "", "| Ingredient | Cost per unit | Vendor | Last updated | Note |", "|---|---|---|---|---|"]
for name, ing in ingredients.items():
    out.append(f"| {name} | ${ing['cost_per_unit']:.4f} / {ing['unit']} | {ing['vendor']} | {ing['last_updated']} | {ing['notes']} |")

if problems:
    out += ["", "## Problems", ""] + [f"- {p}" for p in problems]

(ROOT / "04-cost-breakdown.md").write_text("\n".join(out) + "\n")
print(f"Wrote 04-cost-breakdown.md ({len(drinks)} drinks)")
